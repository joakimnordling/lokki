// Generates src/ui/lucide.js from the lucide-static package: the inner markup of each icon Lokki uses, so the app
// draws them as inline SVG without loading anything. Run after changing NAMES or updating lucide-static:
//   npm run icons
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
export const OUT = join(root, "src", "ui", "lucide.js");
export const NAMES = [
  // header, toolbar and lists
  "grip",
  "settings",
  "chevron-left",
  "chevron-right",
  "square-pen",
  "arrow-down-up",
  "plus",
  "trash-2",
  // sync
  "cloud-check",
  "cloud-upload",
  "cloud-off",
  "cloud-alert",
  "refresh-cw",
  // log types
  "trending-up",
  "utensils",
  "dumbbell",
  "gamepad-2",
  "mountain-snow",
  "cat",
  "shopping-cart",
  "graduation-cap",
  "heart",
  "camera",
  "martini",
  "volleyball",
  "luggage",
  "user",
  "stethoscope",
  "music",
  "circle-dollar-sign",
  "monitor",
];

const pkg = join(root, "node_modules", "lucide-static");
// The elements inside <svg>, on one line: '<path d="M3 6h18"/> <line x1="10" .../>'
export async function inner(name) {
  const svg = await readFile(join(pkg, "icons", `${name}.svg`), "utf8");
  const body = /<svg[^>]*>([\s\S]*)<\/svg>/.exec(svg)[1];
  return body
    .trim()
    .split(/\n\s*/)
    .map((l) => l.replace(/\s*\/>$/, "/>"))
    .join(" ");
}

export async function generate() {
  const { version } = JSON.parse(await readFile(join(pkg, "package.json"), "utf8"));
  const icons = {};
  for (const n of [...NAMES].sort()) icons[n] = await inner(n);
  return `// Generated by scripts/build-icons.js from lucide-static ${version}. Do not edit; run npm run icons.
// Icons: Lucide (https://lucide.dev), ISC License; see THIRD_PARTY_NOTICES.md.
export const LUCIDE = ${JSON.stringify(icons, null, 2)};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeFile(OUT, await generate());
  console.log(`${OUT} (${NAMES.length} icons)`);
}
